import pandas as pd
import duckdb
import random
import matplotlib.pyplot as plt

# 1. Create Data (Instant Version)
print("🚀 Generating data...")
data = []
for i in range(50000):
    # Simulate Hours: Peak is 10-13 (10 AM - 1 PM)
    hour = random.randint(0, 23)
    is_peak = 10 <= hour <= 13

    # Failure Logic: High failure in peak (approx 30%), Low otherwise (approx 10%)
    if is_peak:
        status = 'FAILED' if random.random() < 0.32 else 'SUCCESS'
        reason = 'Bank_Timeout' if status == 'FAILED' and random.random() < 0.70 else ('Insufficient_Funds' if status == 'FAILED' else 'None')
    else:
        status = 'FAILED' if random.random() < 0.12 else 'SUCCESS'
        reason = 'Bank_Timeout' if status == 'FAILED' and random.random() < 0.20 else ('Insufficient_Funds' if status == 'FAILED' else 'None')

    data.append([i, hour, status, reason])

df = pd.DataFrame(data, columns=['id', 'hour', 'status', 'reason'])

# 2. Run Analysis (MySQL Style Logic)
print("📊 Analyzing...")
query_analytics = """
    SELECT
        CASE WHEN hour BETWEEN 10 AND 13 THEN 'Peak (10AM-1PM)' ELSE 'Off-Peak' END as period,
        COUNT(*) as total,
        SUM(CASE WHEN status = 'FAILED' THEN 1 ELSE 0 END) as failures
    FROM df
    GROUP BY 1
"""
results = duckdb.query(query_analytics).df()
results['failure_rate'] = round((results['failures'] / results['total']) * 100, 2)

# 3. Print Results
print("\n" + "="*30)
print("✅ COPY THESE NUMBERS BELOW:")
print("="*30)
print(results.to_string(index=False))
print("="*30)

df.to_csv('/content/subscription_logs.csv', index=False)
print("✅ Dataset successfully saved to storage!")